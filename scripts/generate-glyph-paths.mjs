// Dev-only generator for app/components/scenes/create-glyphs.ts.
//
// Emits the Inter Medium glyph outlines for "yours." as clip-path data
// normalized to each glyph's ink bounding box (objectBoundingBox units),
// plus that bbox in em units relative to the advance origin / baseline.
// The scene positions each media tile on the ink bbox measured from the
// live DOM (span rect left + baseline probe), so no browser font-metric
// assumptions (hhea vs typo ascent) are involved at runtime.
//
// Usage: node scripts/generate-glyph-paths.mjs <path-to-Inter-Medium.ttf>

import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const { parse } = opentype;

const fontPath = process.argv[2];
if (!fontPath) {
  console.error("Usage: node scripts/generate-glyph-paths.mjs <Inter-Medium.ttf>");
  process.exit(1);
}

const font = parse(readFileSync(fontPath).buffer);
const upm = font.unitsPerEm;

const LETTERS = [
  { key: "y", char: "y" },
  { key: "o", char: "o" },
  { key: "u", char: "u" },
  { key: "r", char: "r" },
  { key: "s", char: "s" },
  { key: "dot", char: "." },
];

const round = (n) => Math.round(n * 1e5) / 1e5;

const entries = LETTERS.map(({ key, char }) => {
  const glyph = font.charToGlyph(char);
  // fontSize = upm keeps coordinates in font units, y flipped to point down.
  const path = glyph.getPath(0, 0, upm);
  const bb = path.getBoundingBox();
  const w = bb.x2 - bb.x1;
  const h = bb.y2 - bb.y1;
  const nx = (x) => round((x - bb.x1) / w);
  const ny = (y) => round((y - bb.y1) / h);
  const d = path.commands
    .map((c) => {
      switch (c.type) {
        case "M":
          return `M${nx(c.x)} ${ny(c.y)}`;
        case "L":
          return `L${nx(c.x)} ${ny(c.y)}`;
        case "C":
          return `C${nx(c.x1)} ${ny(c.y1)} ${nx(c.x2)} ${ny(c.y2)} ${nx(c.x)} ${ny(c.y)}`;
        case "Q":
          return `Q${nx(c.x1)} ${ny(c.y1)} ${nx(c.x)} ${ny(c.y)}`;
        case "Z":
          return "Z";
        default:
          throw new Error(`Unhandled path command ${c.type}`);
      }
    })
    .join("");
  return {
    key,
    d,
    // Ink bbox in em, canvas orientation (y down, negative = above baseline),
    // relative to the glyph's advance origin.
    x1: round(bb.x1 / upm),
    y1: round(bb.y1 / upm),
    x2: round(bb.x2 / upm),
    y2: round(bb.y2 / upm),
  };
});

const body = entries
  .map(
    (e) =>
      `  ${e.key}: {\n    d: "${e.d}",\n    x1: ${e.x1},\n    y1: ${e.y1},\n    x2: ${e.x2},\n    y2: ${e.y2},\n  },`,
  )
  .join("\n");

const out = `// Generated by scripts/generate-glyph-paths.mjs from ${font.names.fullName?.en ?? "Inter Medium"} (upm ${upm}).
// Do not edit by hand — re-run the script if the display font changes.
//
// d: glyph outline normalized to its ink bounding box (objectBoundingBox units).
// x1/y1/x2/y2: ink bbox in em, y pointing down, relative to advance origin
// (x) and baseline (y) — y1 is negative above the baseline.

export type CreateGlyph = {
  d: string;
  x1: number;
  y1: number;
  x2: number;
  y2: number;
};

export const CREATE_GLYPHS: Record<string, CreateGlyph> = {
${body}
};
`;

writeFileSync(new URL("../app/components/scenes/create-glyphs.ts", import.meta.url), out);
console.log(`Wrote create-glyphs.ts (${entries.length} glyphs, upm ${upm}).`);
